

#ifndef MSGQUEUE_H
#define MSGQUEUE_H

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <pthread.h>
#include <semaphore.h>
#include <stdbool.h>

// Максимальная длина сообщения, сохраняемого в очереди (ASCIIZ строка до 80 символов + завершающий ноль)
#define MAX_MSG_LEN 81
// Максимальное количество записей в очереди
#define MAX_QUEUE_SIZE 10

/*
--------------------------------------------------
СТРУКТУРА: message_t
НАЗНАЧЕНИЕ: Структура для хранения одного сообщения в очереди
ПОЛЯ:
    data - массив символов для хранения текста сообщения (ASCIIZ строка)
--------------------------------------------------
*/
typedef struct message {
    char data[MAX_MSG_LEN];
} message_t;

/*
--------------------------------------------------
СТРУКТУРА: queue_t
НАЗНАЧЕНИЕ: Структура потокобезопасной очереди сообщений
ПОЛЯ:
    buffer - циклический буфер для хранения сообщений
    head - индекс головы очереди (для чтения/извлечения сообщений)
    tail - индекс хвоста очереди (для записи/добавления сообщений)
    count - текущее количество сообщений в очереди
    mutex - мьютекс для защиты критических секций при доступе к очереди
    full - семафор, отслеживающий количество занятых слотов (для операции извлечения)
    empty - семафор, отслеживающий количество свободных слотов (для операции добавления)
    dropped - флаг, указывающий на выполнение операции drop (очистки очереди)
    drop_cond - условная переменная для уведомления потоков об операции drop
--------------------------------------------------
*/
typedef struct queue {
    message_t buffer[MAX_QUEUE_SIZE]; // Буфер для хранения сообщений
    int head; // Индекс головы (для чтения/get)
    int tail; // Индекс хвоста (для записи/put)
    int count; // Текущее количество элементов в очереди
    
    pthread_mutex_t mutex; // Мьютекс для защиты критической секции (самой очереди)
    sem_t full; // Семафор: количество занятых слотов (для get)
    sem_t empty; // Семафор: количество свободных слотов (для put)
    
    bool dropped; // Флаг для mymsgdrop
    pthread_cond_t drop_cond; // Условная переменная для уведомления о drop (в mymsgdrop)

} queue_t;

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsginit
НАЗНАЧЕНИЕ: Инициализация очереди сообщений и всех связанных синхронизационных примитивов
ИСПОЛЬЗОВАНИЕ ПАРАМЕТРОВ:
    q - указатель на очередь сообщений для инициализации
--------------------------------------------------
*/
void mymsginit(queue_t *q);

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsqdrop
НАЗНАЧЕНИЕ: Очистка всех сообщений из очереди и сброс ее состояния
ИСПОЛЬЗОВАНИЕ ПАРАМЕТРОВ:
    q - указатель на очередь сообщений для очистки
--------------------------------------------------
*/
void mymsqdrop(queue_t *q);

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsgdestroy
НАЗНАЧЕНИЕ: Полное уничтожение очереди сообщений с освобождением всех ресурсов
ИСПОЛЬЗОВАНИЕ ПАРАМЕТРОВ:
    q - указатель на очередь сообщений для уничтожения
--------------------------------------------------
*/
void mymsgdestroy(queue_t *q);

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsgput
НАЗНАЧЕНИЕ: Добавление нового сообщения в очередь (потокобезопасная операция)
ИСПОЛЬЗОВАНИЕ ПАРАМЕТРОВ:
    q - указатель на очередь сообщений
    msg - строка с сообщением для добавления
ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
    Количество успешно записанных символов (0 при ошибке)
--------------------------------------------------
*/
int mymsgput(queue_t *q, char *msg);

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsgget
НАЗНАЧЕНИЕ: Извлечение сообщения из очереди (потокобезопасная операция)
ИСПОЛЬЗОВАНИЕ ПАРАМЕТРОВ:
    q - указатель на очередь сообщений
    buf - буфер для сохранения извлеченного сообщения
    bufsize - размер буфера для сохранения сообщения
ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
    Количество успешно прочитанных символов (0 при ошибке)
--------------------------------------------------
*/
int mymsgget(queue_t *q, char *buf, size_t bufsize);

#endif // MSGQUEUE_H
