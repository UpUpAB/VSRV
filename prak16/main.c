#include "msgqueue.h"
#include <unistd.h> // для usleep

// Глобальная очередь
queue_t message_queue;

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: producer_func
НАЗНАЧЕНИЕ: Функция потока-производителя, добавляющего сообщения в очередь
ИСПОЛЬЗОВАНИЕ ПАРАМЕТРОВ:
    arg - указатель на идентификатор производителя
ВЫЗЫВАЕМЫЕ ФУНКЦИИ:
    mymsgput() - добавление сообщения в потокобезопасную очередь
    snprintf() - форматирование тестового сообщения
    printf() - вывод информации о работе производителя
    usleep() - случайная пауза между отправкой сообщений
    rand() - генерация случайного времени паузы
--------------------------------------------------
*/
void *producer_func(void *arg) {
    int id = *(int*)arg;
    char msg[100];
    int i;
    
    printf("Производитель #%d запущен.\n", id);

    for (i = 0; i < 20; i++) {
        // Создание сообщения
        snprintf(msg, sizeof(msg), "[%d-%d] Сообщение от Производителя #%d. Тестовая строка для обрезки: XXXXXXXXXXXXXXXXXXXXXXXXXXX", id, i, id);
        
        // Попытка поместить сообщение
        int len = mymsgput(&message_queue, msg);
        
        if (len > 0) {
            printf("  [P%d] -> Отправил: '%s...' (%d символов)\n", id, msg, len);
        } else if (message_queue.dropped) {
            printf("  [P%d] Отменено из-за drop (попытка #%d)\n", id, i);
            break;
        }
        
        // Пауза, чтобы другие нити могли работать
        usleep(rand() % 200000); // 0.2 секунды
    }
    
    printf("Производитель #%d завершил работу.\n", id);
    return NULL;
}

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: consumer_func
НАЗНАЧЕНИЕ: Функция потока-потребителя, извлекающего сообщения из очереди
ИСПОЛЬЗОВАНИЕ ПАРАМЕТРОВ:
    arg - указатель на идентификатор потребителя
ВЫЗЫВАЕМЫЕ ФУНКЦИИ:
    mymsgget() - извлечение сообщения из потокобезопасной очереди
    printf() - вывод информации о работе потребителя и состоянии очереди
    usleep() - случайная пауза между получением сообщений
    rand() - генерация случайного времени паузы
--------------------------------------------------
*/
void *consumer_func(void *arg) {
    int id = *(int*)arg;
    // Максимальный размер буфера потребителя - 40 символов + '\0'
    char buf[41];
    int i;
    
    printf("Потребитель #%d запущен.\n", id);

    for (i = 0; i < 30; i++) {
        // Попытка получить сообщение
        int len = mymsgget(&message_queue, buf, sizeof(buf));
        
        if (len > 0) {
            printf("  [C%d] <- Получил: '%s' (%d символов) | Длина очереди: %d\n",
                   id, buf, len, message_queue.count);
        } else if (message_queue.dropped) {
            printf("  [C%d] Отменено из-за drop (попытка #%d)\n", id, i);
            break;
        }

        // Пауза
        usleep(rand() % 300000); // 0.3 секунды
    }
    
    printf("Потребитель #%d завершил работу.\n", id);
    return NULL;
}

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: main
НАЗНАЧЕНИЕ: Главная функция тестовой программы для проверки очереди сообщений
ВЫЗЫВАЕМЫЕ ФУНКЦИИ:
    mymsginit() - инициализация глобальной очереди сообщений
    pthread_create() - создание потоков производителей и потребителей
    pthread_join() - ожидание завершения всех потоков
    mymsqdrop() - опциональная очистка очереди во время работы (закомментирована)
    mymsgdestroy() - уничтожение очереди и освобождение ресурсов
    srand() - инициализация генератора случайных чисел
    time() - получение текущего времени для инициализации генератора
    sleep() - пауза перед возможным вызовом функции drop
    printf() - вывод информации о ходе выполнения теста
--------------------------------------------------
*/
int main() {
    // Инициализация генератора случайных чисел
    srand(time(NULL));

    // 1. Инициализация очереди
    mymsginit(&message_queue);

    // Массивы для нитей и их ID
    pthread_t producers[2];
    pthread_t consumers[2];
    int producer_ids[2] = {1, 2};
    int consumer_ids[2] = {1, 2};

    // 2. Создание нитей Производителей и Потребителей
    printf("--- Запуск 2 Производителей и 2 Потребителей ---\n");
    
    int i;
    for (i = 0; i < 2; i++) {
        pthread_create(&producers[i], NULL, producer_func, &producer_ids[i]);
        pthread_create(&consumers[i], NULL, consumer_func, &consumer_ids[i]);
    }
    
    // Добавим короткую паузу и вызовем mymsqdrop для демонстрации
    sleep(4); // Ждем 4 секунды
    // mymsqdrop(&message_queue); // Раскомментируйте для демонстрации mymsqdrop

    // 3. Ожидание завершения нитей
    for (i = 0; i < 2; i++) {
        pthread_join(producers[i], NULL);
        pthread_join(consumers[i], NULL);
    }

    printf("\n--- Все нити завершили работу ---\n");
    
    // 4. Уничтожение очереди
    mymsgdestroy(&message_queue);

    return 0;
}
