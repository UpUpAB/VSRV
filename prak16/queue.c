#ifndef MSGQUEUE_H
#define MSGQUEUE_H

#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <pthread.h>
#include <stdbool.h>
#include <unistd.h>
#include <time.h>

// Максимальная длина сообщения, сохраняемого в очереди (ASCII СТРОКА до 30 символов + завершающий ноль)
#define MAX_MSG_LEN 31
// Максимальное количество записей в очереди
#define MAX_QUEUE_SIZE 10

/*
--------------------------------------------------
СТРУКТУРА: message_t
НАЗНАЧЕНИЕ: Структура для хранения одного сообщения в очереди
ПОЛЯ:
    data - массив символов для хранения текста сообщения (ASCIIZ строка)
--------------------------------------------------
*/
typedef struct message {
    char data[MAX_MSG_LEN];
} message_t;

/*
--------------------------------------------------
СТРУКТУРА: queue_t
НАЗНАЧЕНИЕ: Структура потокобезопасной очереди сообщений с использованием условных переменных
ПОЛЯ:
    buffer - циклический буфер для хранения сообщений
    head - индекс головы очереди (для чтения/извлечения сообщений)
    tail - индекс хвоста очереди (для записи/добавления сообщений)
    count - текущее количество сообщений в очереди
    mutex - мьютекс для защиты критических секций при доступе к очереди
    not_empty - условная переменная для сигнализации о наличии сообщений в очереди
    not_full - условная переменная для сигнализации о наличии свободного места
    dropped - флаг, указывающий на выполнение операции drop (очистки очереди)
--------------------------------------------------
*/
typedef struct queue {
    message_t buffer[MAX_QUEUE_SIZE];
    int head;
    int tail;
    int count;

    pthread_mutex_t mutex;
    pthread_cond_t not_empty; // Сигнал, что очередь не пуста
    pthread_cond_t not_full;  // Сигнал, что очередь не полна

    bool dropped; // Флаг, указывающий, что очередь сброшена
} queue_t;

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsginit
НАЗНАЧЕНИЕ: Инициализация очереди сообщений и всех связанных синхронизационных примитивов
ИСПОЛЬЗОВАНИЕ ПАРАМЕТРОВ:
    q - указатель на очередь сообщений для инициализации
--------------------------------------------------
*/
void mymsginit(queue_t *q);

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsgdrop
НАЗНАЧЕНИЕ: Очистка всех сообщений из очереди и сброс ее состояния
ИСПОЛЬЗОВАНИЕ ПАРАМЕТРОВ:
    q - указатель на очередь сообщений для очистки
--------------------------------------------------
*/
void mymsgdrop(queue_t *q);

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsgdestroy
НАЗНАЧЕНИЕ: Полное уничтожение очереди сообщений с освобождением всех ресурсов
ИСПОЛЬЗОВАНИЕ ПАРАМЕТРОВ:
    q - указатель на очередь сообщений для уничтожения
--------------------------------------------------
*/
void mymsgdestroy(queue_t *q);

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsgput
НАЗНАЧЕНИЕ: Добавление нового сообщения в очередь (потокобезопасная операция)
ИСПОЛЬЗОВАНИЕ ПАРАМЕТРОВ:
    q - указатель на очередь сообщений
    msg - строка с сообщением для добавления
ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
    Количество успешно записанных символов (0 при ошибке или выполнении drop)
--------------------------------------------------
*/
int mymsgput(queue_t *q, char *msg);

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsgget
НАЗНАЧЕНИЕ: Извлечение сообщения из очереди (потокобезопасная операция)
ИСПОЛЬЗОВАНИЕ ПАРАМЕТРОВ:
    q - указатель на очередь сообщений
    buf - буфер для сохранения извлеченного сообщения
    bufsize - размер буфер для сохранения сообщения
ВОЗВРАЩАЕМОЕ ЗНАЧЕНИЕ:
    Количество успешно прочитанных символов (0 при ошибке или выполнении drop)
--------------------------------------------------
*/
int mymsgget(queue_t *q, char *buf, size_t bufsize);

#endif // MSGQUEUE_H

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsginit
ВЫЗЫВАЕМЫЕ ФУНКЦИИ:
    pthread_mutex_init() - инициализация мьютекса для защиты критических секций
    pthread_cond_init() - инициализация условных переменных для синхронизации
    perror() - обработка ошибок инициализации синхронизационных примитивов
    exit() - аварийное завершение программы при критических ошибках инициализации
--------------------------------------------------
*/
void mymsginit(queue_t *q) {
    q->head = 0;
    q->tail = 0;
    q->count = 0;
    q->dropped = false;

    if (pthread_mutex_init(&(q->mutex), NULL) != 0) {
        perror("pthread_mutex_init failed");
        exit(EXIT_FAILURE);
    }

    if (pthread_cond_init(&(q->not_empty), NULL) != 0) {
        perror("pthread_cond_init not_empty failed");
        exit(EXIT_FAILURE);
    }

    if (pthread_cond_init(&(q->not_full), NULL) != 0) {
        perror("pthread_cond_init not_full failed");
        exit(EXIT_FAILURE);
    }
}

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsgput
ВЫЗЫВАЕМЫЕ ФУНКЦИИ:
    pthread_mutex_lock() - захват мьютекса для защиты критической секции
    pthread_mutex_unlock() - освобождение мьютекса
    pthread_cond_wait() - ожидание свободного места при полной очереди
    pthread_cond_signal() - оповещение потребителей о появлении нового сообщения
    strnlen() - определение длины строки с ограничением
    strncpy() - копирование строки в буфер очереди
--------------------------------------------------
*/
int mymsgput(queue_t *q, char *msg) {
    pthread_mutex_lock(&(q->mutex));

    // Ждем, пока появится свободное место или пока не будет вызван drop
    while (q->count == MAX_QUEUE_SIZE && !q->dropped) {
        pthread_cond_wait(&(q->not_full), &(q->mutex));
    }

    // Если был вызван drop, возвращаем 0
    if (q->dropped) {
        pthread_mutex_unlock(&(q->mutex));
        return 0;
    }

    // Копируем сообщение
    // Убедимся, что не превышаем MAX_MSG_LEN
    size_t msg_len = strnlen(msg, MAX_MSG_LEN - 1);
    
    // Копируем сообщение в буфер очереди
    strncpy(q->buffer[q->tail].data, msg, msg_len);
    q->buffer[q->tail].data[msg_len] = '\0'; // Гарантируем завершающий ноль

    q->tail = (q->tail + 1) % MAX_QUEUE_SIZE;
    q->count++;

    // Сигнализируем, что очередь не пуста
    pthread_cond_signal(&(q->not_empty));
    pthread_mutex_unlock(&(q->mutex));

    return (int)msg_len;
}

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsgget
ВЫЗЫВАЕМЫЕ ФУНКЦИИ:
    pthread_mutex_lock() - захват мьютекса для защиты критической секции
    pthread_mutex_unlock() - освобождение мьютекса
    pthread_cond_wait() - ожидание сообщений при пустой очереди
    pthread_cond_signal() - оповещение производителей об освобождении места
    strnlen() - определение длины строки в буфере очереди
    strncpy() - копирование строки в пользовательский буфер
--------------------------------------------------
*/
int mymsgget(queue_t *q, char *buf, size_t bufsize) {
    pthread_mutex_lock(&(q->mutex));

    // Ждем, пока появится сообщение или пока не будет вызван drop
    while (q->count == 0 && !q->dropped) {
        pthread_cond_wait(&(q->not_empty), &(q->mutex));
    }

    // Если был вызван drop, возвращаем 0
    if (q->dropped) {
        pthread_mutex_unlock(&(q->mutex));
        return 0;
    }

    // Копируем сообщение в буфер пользователя.
    // Вычисляем длину сообщения в очереди
    size_t stored_len = strnlen(q->buffer[q->head].data, MAX_MSG_LEN - 1);
    
    // Определяем, сколько символов копировать:
    // минимум из (длина сообщения в очереди) и (размер буфера пользователя - 1)
    size_t copy_len = (stored_len < bufsize - 1) ? stored_len : (bufsize - 1);

    // Копируем данные
    strncpy(buf, q->buffer[q->head].data, copy_len);
    buf[copy_len] = '\0'; // Гарантируем завершающий ноль в буфере пользователя

    q->head = (q->head + 1) % MAX_QUEUE_SIZE;
    q->count--;

    // Сигнализируем, что появилось свободное место
    pthread_cond_signal(&(q->not_full));
    pthread_mutex_unlock(&(q->mutex));

    return (int)copy_len;
}

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsgdrop
ВЫЗЫВАЕМЫЕ ФУНКЦИИ:
    pthread_mutex_lock() - захват мьютекса для защиты операции drop
    pthread_mutex_unlock() - освобождение мьютекса
    pthread_cond_broadcast() - оповещение всех ожидающих потоков об операции drop
    printf() - уведомление о выполнении операции drop
--------------------------------------------------
*/
void mymsgdrop(queue_t *q) {
    pthread_mutex_lock(&(q->mutex));

    q->dropped = true; // Устанавливаем флаг сброса

    // Разблокируем все ожидающие потоки:
    // Производителей (not_full) и Потребителей (not_empty)
    pthread_cond_broadcast(&(q->not_empty));
    pthread_cond_broadcast(&(q->not_full));

    pthread_mutex_unlock(&(q->mutex));

    printf("\n>>> ОЧЕРЕДЬ СБРОШЕНА (DROP). Get/Put возвращают 0. <<<\n\n");
}

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: mymsgdestroy
ВЫЗЫВАЕМЫЕ ФУНКЦИИ:
    pthread_mutex_destroy() - уничтожение мьютекса
    pthread_cond_destroy() - уничтожение условных переменных
    printf() - уведомление об успешном уничтожении очереди
--------------------------------------------------
*/
void mymsgdestroy(queue_t *q) {
    pthread_mutex_destroy(&(q->mutex));
    pthread_cond_destroy(&(q->not_empty));
    pthread_cond_destroy(&(q->not_full));

    printf("Очередь уничтожена.\n");
}

/*
--------------------------------------------------
ОБЪЯВЛЕНИЕ ГЛОБАЛЬНЫХ ПЕРЕМЕННЫХ:
message_queue - глобальная очередь сообщений для тестирования
--------------------------------------------------
*/
queue_t message_queue;

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: producer_func
ВЫЗЫВАЕМЫЕ ФУНКЦИИ:
    mymsgput() - добавление сообщения в потокобезопасную очередь
    snprintf() - форматирование тестового сообщения
    printf() - вывод информации о работе производителя
    usleep() - случайная пауза между отправкой сообщений
    rand() - генерация случайного времени паузы
--------------------------------------------------
*/
void *producer_func(void *arg) {
    int id = *((int*)arg);
    char msg[100]; // Буфер для сообщения
    int i;

    printf("Производитель #%d запущен.\n", id);

    for (i = 0; i < 20; i++) {
        // Формируем сообщение
        snprintf(msg, sizeof(msg), "[%d-%d] Сообщение от Производителя #%d", id, i, id);

        // Помещаем сообщение в очередь
        int len = mymsgput(&message_queue, msg);

        if (len > 0) {
            printf("[%d] -> Отправил: '%s' (%d символов)\n", id, msg, len);
        } else {
            // mymsgput вернул 0, т.к. был вызван drop
            printf("[%d] Отменено из-за drop (попытка #%d)\n", id, i);
            break; // Выход из цикла после drop
        }

        // Случайная задержка до 200,000 микросекунд (0.2 сек)
        usleep(rand() % 200000);
    }

    printf("Производитель #%d завершил работу.\n", id);
    return NULL;
}

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: consumer_func
ВЫЗЫВАЕМЫЕ ФУНКЦИИ:
    mymsgget() - извлечение сообщения из потокобезопасной очереди
    printf() - вывод информации о работе потребителя и состоянии очереди
    usleep() - случайная пауза между получением сообщений
    rand() - генерация случайного времени паузы
--------------------------------------------------
*/
void *consumer_func(void *arg) {
    int id = *((int*)arg);
    char buf[41]; // Буфер для полученного сообщения (30 символов + '\0' из-за MAX_MSG_LEN=31, bufsize=41)
    int i;

    printf("Потребитель #%d запущен.\n", id);

    for (i = 0; i < 30; i++) {
        // Извлекаем сообщение из очереди
        int len = mymsgget(&message_queue, buf, sizeof(buf));

        if (len > 0) {
            // Вывод информации о полученном сообщении
            printf("[%d] <- Получил: '%s' (%d символов) | Длина очереди: %d\n",
                   id, buf, len, message_queue.count);
        } else {
            // mymsgget вернул 0, т.к. был вызван drop
            printf("[%d] Отменено из-за drop (попытка #%d)\n", id, i);
            break; // Выход из цикла после drop
        }

        // Случайная задержка до 300,000 микросекунд (0.3 сек)
        usleep(rand() % 300000);
    }

    printf("Потребитель #%d завершил работу.\n", id);
    return NULL;
}

/*
--------------------------------------------------
НАЗНАЧЕНИЕ ФУНКЦИИ: main
ВЫЗЫВАЕМЫЕ ФУНКЦИИ:
    mymsginit() - инициализация глобальной очереди сообщений
    pthread_create() - создание потоков производителей и потребителей
    pthread_join() - ожидание завершения всех потоков
    mymsgdrop() - принудительная очистка очереди во время работы
    mymsgdestroy() - уничтожение очереди и освобождение ресурсов
    srand() - инициализация генератора случайных чисел
    time() - получение текущего времени для инициализации генератора
    sleep() - пауза перед вызовом функции drop
    printf() - вывод информации о ходе выполнения теста
--------------------------------------------------
*/
int main() {
    // Инициализируем генератор случайных чисел
    srand((unsigned int)time(NULL));

    // Инициализируем очередь
    mymsginit(&message_queue);

    // Объявляем переменные для потоков и их ID
    pthread_t producers[2];
    pthread_t consumers[2];
    int producer_ids[2] = {1, 2};
    int consumer_ids[2] = {1, 2};

    printf("--- Запуск 2 Производителей и 2 Потребителей ---\n");

    int i;
    // Создание потоков-производителей
    for (i = 0; i < 2; i++) {
        pthread_create(&producers[i], NULL, producer_func, &producer_ids[i]);
    }
    // Создание потоков-потребителей
    for (i = 0; i < 2; i++) {
        pthread_create(&consumers[i], NULL, consumer_func, &consumer_ids[i]);
    }

    // Ждем 2 секунды
    sleep(2);
    
    // Вызываем drop, который разблокирует все ждущие потоки (Producer/Consumer)
    printf("\nВызываем mymsgdrop через 2 секунды...\n");
    mymsgdrop(&message_queue);

    // Ожидание завершения потоков
    for (i = 0; i < 2; i++) {
        pthread_join(producers[i], NULL);
        pthread_join(consumers[i], NULL);
    }

    printf("\n--- Все нити завершили работу ---\n");

    // Уничтожаем очередь
    mymsgdestroy(&message_queue);

    return 0;
}
